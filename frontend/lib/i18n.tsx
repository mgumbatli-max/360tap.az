const LangContext = createContext<{ lang: Lang; setLang: (l: Lang) => void; t: (key: string) => string }>({
  lang: 'az',
  setLang: () => {},
  t: (k) => k,
});

export function LangProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>('az');

  useEffect(() => {
    try {
      const saved = localStorage.getItem(KEY) as Lang;
      if (saved && ['az','ru','en'].includes(saved)) setLangState(saved);
    } catch {}
  }, []);

  const setLang = (l: Lang) => {
    setLangState(l);
    try { localStorage.setItem(KEY, l); } catch {}
    document.documentElement.lang = l === 'az' ? 'az-AZ' : l;
  };

  const t = (key: string) => dict[lang]?.[key] ?? dict.az[key] ?? key;

  return <LangContext.Provider value={{ lang, setLang, t }}>{children}</LangContext.Provider>;
}

export function useT() {
  return useContext(LangContext);
}
